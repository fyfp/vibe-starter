// Deterministic candle generator for realistic historical charting
export function generateCandles(basePrice: number, count: number = 60, volatility: number = 0.015): Candle[] {
  const candles: Candle[] = [];
  let currentPrice = basePrice * (1 - volatility * (count / 2) * 0.1);
  const now = new Date('2026-11-11T16:00:00Z').getTime();
  const intervalMs = 60 * 60 * 1000; // 1-hour candles

  for (let i = count; i >= 0; i--) {
    const time = new Date(now - i * intervalMs).toISOString();
    // Pseudo-random deterministic walk
    const seed = Math.sin(i * 12.9898 + basePrice * 78.233);
    const change = currentPrice * volatility * (seed * 1.8 - 0.7);
    const open = currentPrice;
    const close = Math.max(0.01, open + change);
    const high = Math.max(open, close) + Math.abs(change) * (0.3 + Math.abs(seed) * 0.6);
    const low = Math.min(open, close) - Math.abs(change) * (0.2 + (1 - Math.abs(seed)) * 0.5);
    const volume = Math.floor(10000 + Math.abs(seed) * 90000 * (basePrice > 1000 ? 5 : 50));

    candles.push({
      time: time.slice(11, 16),
      open: Number(open.toFixed(basePrice < 2 ? 4 : 2)),
      high: Number(high.toFixed(basePrice < 2 ? 4 : 2)),
      low: Number(low.toFixed(basePrice < 2 ? 4 : 2)),
      close: Number(close.toFixed(basePrice < 2 ? 4 : 2)),
      volume,
    });

    currentPrice = close;
  }

  // Ensure last candle matches basePrice
  if (candles.length > 0) {
    candles[candles.length - 1].close = basePrice;
    candles[candles.length - 1].high = Math.max(candles[candles.length - 1].high, basePrice);
    candles[candles.length - 1].low = Math.min(candles[candles.length - 1].low, basePrice);
  }

  return candles;
}

